-- 1. Catálogo de Servicios
IF OBJECT_ID('dbo.BGD_MTZ3100_SERVICIOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BGD_MTZ3100_SERVICIOS (
        COD_SERVICIO VARCHAR(10) NOT NULL PRIMARY KEY,
        NOMBRE_SERVICIO NVARCHAR(150) NOT NULL,
        CATEGORIA NVARCHAR(100) NULL,
        ESTADO VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
        [FECHA CARGA] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
    );
END;

-- 2. Colaboradores por Sede
IF OBJECT_ID('dbo.BGD_MTZ_COL', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BGD_MTZ_COL (
        CEDULA NVARCHAR(12) NOT NULL,
        SEDE VARCHAR(50) NOT NULL,
        NOMBRE_COLABORADOR NVARCHAR(200) NOT NULL,
        CODIGO NVARCHAR(50) NULL,
        ESTADO NVARCHAR(50) NULL,
        CARGO NVARCHAR(150) NOT NULL,
        COD_SERVICIO VARCHAR(10) NOT NULL,
        [JEFE INMEDIATO] NVARCHAR(200) NOT NULL,
        [FECHA CARGA] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_BGD_MTZ_COL PRIMARY KEY (CEDULA, SEDE)
    );

    CREATE NONCLUSTERED INDEX IX_BGD_MTZ_COL_JEFE 
    ON dbo.BGD_MTZ_COL (SEDE, [JEFE INMEDIATO]);
END;

-- 3. Jefes Inmediatos (BDG_MTZ_JEFE)
IF OBJECT_ID('dbo.BDG_MTZ_JEFE', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BDG_MTZ_JEFE (
        CEDULA NVARCHAR(12) NULL,
        [NOMBRE DEL JEFE] NVARCHAR(200) NOT NULL,
        SEDE VARCHAR(50) NOT NULL,
        VARIANTES NVARCHAR(MAX) NULL,
        REPETIDOS INT NOT NULL DEFAULT 1,
        [FECHA CARGA] DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
    );

    CREATE NONCLUSTERED INDEX IX_BDG_MTZ_JEFE_SEDE 
    ON dbo.BDG_MTZ_JEFE (SEDE, [NOMBRE DEL JEFE]);
END;

-- 4. Dashboard Central de Cursos (BGD_MTZ3100_DASH)
IF OBJECT_ID('dbo.BGD_MTZ3100_DASH', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BGD_MTZ3100_DASH (
        ID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        MES_ANALISIS VARCHAR(10) NOT NULL,
        CEDULA NVARCHAR(12) NOT NULL,
        NOMBRE_COLABORADOR NVARCHAR(200) NOT NULL,
        COD_SERVICIO VARCHAR(10) NULL,
        NOMBRE_SERVICIO NVARCHAR(150) NULL,
        SEDE VARCHAR(50) NOT NULL,
        MULTISEDE VARCHAR(5) NULL DEFAULT 'NO',
        CURSO_ID VARCHAR(10) NOT NULL,
        CURSO_NOMBRE NVARCHAR(150) NOT NULL,
        MARCA_ORIGEN VARCHAR(20) NULL,
        FECHA_REAL_ORIGEN DATE NULL,
        FECHA_VENC_ORIGEN DATE NULL,
        LECTURA VARCHAR(20) NULL,
        OBLIGATORIO VARCHAR(2) NOT NULL DEFAULT 'SI',
        VIGENCIA_MESES INT NOT NULL,
        VENC_EFECTIVO DATE NULL,
        REAL_EFECTIVA DATE NULL,
        ESTADO_DETALLADO VARCHAR(30) NOT NULL,
        MARCA VARCHAR(10) NOT NULL,
        DIAS_PARA_VENCER INT NULL,
        CUENTA_INDICADOR INT NOT NULL DEFAULT 0,
        ALERTA VARCHAR(50) NULL,
        OBSERVACION NVARCHAR(500) NULL,
        SUBSANADO_CONTROL_CALIDAD INT NULL,
        FECHA_CALCULO DATETIME2 NULL DEFAULT SYSUTCDATETIME()
    );

    CREATE UNIQUE NONCLUSTERED INDEX IX_BGD_DASH_MERGE 
    ON dbo.BGD_MTZ3100_DASH (MES_ANALISIS, SEDE, CEDULA, CURSO_ID);
END;

-- 5. Resumen Mensual de Cumplimiento (BGD_MTZ3100_RESUMEN)
IF OBJECT_ID('dbo.BGD_MTZ3100_RESUMEN', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.BGD_MTZ3100_RESUMEN (
        ID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        MES_ANALISIS VARCHAR(10) NOT NULL,
        FECHA_CORTE DATE NOT NULL,
        SEDE VARCHAR(50) NOT NULL,
        CEDULA NVARCHAR(12) NOT NULL,
        NOMBRE_COLABORADOR NVARCHAR(200) NOT NULL,
        COD_SERVICIO VARCHAR(10) NULL,
        NOMBRE_SERVICIO NVARCHAR(150) NULL,
        MULTISEDE VARCHAR(5) NULL DEFAULT 'NO',
        OBLIGATORIOS INT NOT NULL DEFAULT 0,
        VIGENTES INT NOT NULL DEFAULT 0,
        POR_VENCER INT NOT NULL DEFAULT 0,
        CUMPLE_SIN_FECHA INT NOT NULL DEFAULT 0,
        VENCIDOS INT NOT NULL DEFAULT 0,
        NO_REALIZADOS INT NOT NULL DEFAULT 0,
        SIN_REGISTRO INT NOT NULL DEFAULT 0,
        CUMPLIDOS INT NOT NULL DEFAULT 0,
        PCT_CUMPLIMIENTO DECIMAL(5,2) NOT NULL DEFAULT 0.00,
        ALERTAS VARCHAR(250) NULL,
        CURSOS_PENDIENTES NVARCHAR(MAX) NULL,
        FECHA_CALCULO DATETIME2 NULL DEFAULT SYSUTCDATETIME()
    );

    CREATE UNIQUE NONCLUSTERED INDEX IX_BGD_RESUMEN_MES_CEDULA 
    ON dbo.BGD_MTZ3100_RESUMEN (MES_ANALISIS, SEDE, CEDULA);
END;

PRINT 'Tablas e índices de la nueva arquitectura verificados exitosamente.';

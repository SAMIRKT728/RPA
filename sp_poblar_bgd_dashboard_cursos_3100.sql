    EvaluacionBase AS (
        SELECT 
            u.*,
            dt.VENC_EFECTIVO,
            dt.REAL_EFECTIVA,
            obl.ES_OBLIGATORIO,
            cc.ID AS ID_CONTROL_CALIDAD,
            cc.MOTIVO AS MOTIVO_CONTROL_CALIDAD

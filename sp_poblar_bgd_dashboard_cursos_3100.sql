            END AS MARCA_ORIGEN,

            CASE 
                WHEN v.FECHA_REAL IS NOT NULL AND (YEAR(v.FECHA_REAL) < 2000 OR YEAR(v.FECHA_REAL) > 2040) THEN NULL
                ELSE CAST(v.FECHA_REAL AS DATE)
            END AS FECHA_REAL_ORIGEN,

            CASE 
                WHEN v.FECHA_VENC IS NOT NULL AND (YEAR(v.FECHA_VENC) < 2000 OR YEAR(v.FECHA_VENC) > 2040) THEN NULL
                ELSE CAST(v.FECHA_VENC AS DATE)
            END AS FECHA_VENC_ORIGEN,

            CASE 
                WHEN (v.FECHA_REAL IS NOT NULL AND (YEAR(v.FECHA_REAL) < 2000 OR YEAR(v.FECHA_REAL) > 2040))
                  OR (v.FECHA_VENC IS NOT NULL AND (YEAR(v.FECHA_VENC) < 2000 OR YEAR(v.FECHA_VENC) > 2040)) THEN 1
                ELSE 0
            END AS FECHA_FUERA_DE_RANGO,

            CASE WHEN v.MARCA_ORIGEN = 'SIN_COLUMNA' THEN 'SIN_COLUMNA' ELSE 'OK' END AS LECTURA,
            v.VIGENCIA_MESES
        FROM ConsolidadoMatricesDeduplicado c
        CROSS APPLY (
            VALUES
                ('C01', 'BLS', c.M_C01, c.R_C01, c.V_C01, 24),

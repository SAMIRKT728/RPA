            SELECT 
                CASE 
                    WHEN u.CARGO_NORMALIZADO COLLATE Modern_Spanish_CI_AI = 'ENFERMERO (A) JEFE SERVICIO SOCIAL OBLIGATORIO' 
                        THEN 'ENFERMERO (A) JEFE'
                    WHEN u.CARGO_NORMALIZADO COLLATE Modern_Spanish_CI_AI IN ('MEDICO SERVICIO SOCIAL OBLIGATORIO', 'MEDICO SERVICIO OBLIGATORIO') 
                        THEN 'MEDICO GENERAL'
                    ELSE u.CARGO_NORMALIZADO
                END AS CARGO_NORMATIVO
        ) h
        CROSS APPLY (
            SELECT 
                CASE 
                    -- 1. Si el cargo normativo FIGURA en INDICE_OBLIGATORIEDAD:
                    -- Se rige ÚNICA Y EXCLUSIVAMENTE por lo que la tabla dicta para su cargo normativo y servicio.
                    -- No se fuerza ningún curso como obligatorio por tener marca 'SI' si la norma no lo exige para ese cargo/servicio.
                    WHEN EXISTS (
                        SELECT 1 
                        FROM dbo.INDICE_OBLIGATORIEDAD ind
                        WHERE ind.ESTADO = 'ACTIVO'
                          AND ind.CARGO COLLATE Modern_Spanish_CI_AI = h.CARGO_NORMATIVO COLLATE Modern_Spanish_CI_AI
                    ) THEN
                        CASE 
                            WHEN EXISTS (
                                SELECT 1 
                                FROM dbo.INDICE_OBLIGATORIEDAD ind
                                WHERE ind.ESTADO = 'ACTIVO'
                                  AND ind.CARGO COLLATE Modern_Spanish_CI_AI = h.CARGO_NORMATIVO COLLATE Modern_Spanish_CI_AI
                                  AND ind.CURSO COLLATE Modern_Spanish_CI_AI = u.CURSO_PLANTILLA COLLATE Modern_Spanish_CI_AI
                                  AND (
                                      ind.CODIGOS_SERVICIO = 'TODOS'
                                      OR (
                                          u.COD_SERVICIO IS NOT NULL AND u.COD_SERVICIO <> ''
                                          AND (
                                              ';' + ind.CODIGOS_SERVICIO + ';' LIKE '%;' + u.COD_SERVICIO + ';%'
                                              OR (TRY_CAST(u.COD_SERVICIO AS INT) IS NOT NULL 
                                                  AND ';' + ind.CODIGOS_SERVICIO + ';' LIKE '%;' + RIGHT('0000' + CAST(TRY_CAST(u.COD_SERVICIO AS INT) AS VARCHAR(10)), 4) + ';%')
                                              OR (TRY_CAST(u.COD_SERVICIO AS INT) IS NOT NULL 
                                                  AND ';' + ind.CODIGOS_SERVICIO + ';' LIKE '%;' + CAST(TRY_CAST(u.COD_SERVICIO AS INT) AS VARCHAR(10)) + ';%')
                                          )
                                      )
                                  )
                            ) THEN 1
                            ELSE 0
                        END

                    -- 2. Si el cargo NO figura en INDICE_OBLIGATORIEDAD (roles no asistenciales / administrativos sin norma 3100):
                    -- Los cursos obligatorios se determinan exclusivamente por su marca de origen registrada ('SI' y 'NO' son obligatorios, 'N/A' y vacíos no aplican).
                    ELSE
                        CASE 
                            WHEN u.MARCA_ORIGEN IN ('SI', 'NO') THEN 1
                            ELSE 0
                        END
                END AS ES_OBLIGATORIO
        ) obl
        CROSS APPLY (
            SELECT 
                COALESCE(cc.FECHA_VENC, u.FECHA_VENC_ORIGEN, 
                         CASE WHEN COALESCE(cc.FECHA_REAL, u.FECHA_REAL_ORIGEN) IS NOT NULL 
                              THEN DATEADD(month, u.VIGENCIA_MESES, COALESCE(cc.FECHA_REAL, u.FECHA_REAL_ORIGEN)) 
                              ELSE NULL END
                ) AS VENC_EFECTIVO,
                COALESCE(cc.FECHA_REAL, u.FECHA_REAL_ORIGEN) AS REAL_EFECTIVA
        ) dt
    ),
    EvaluacionSituaciones AS (
        SELECT 
            eb.*,
            CASE 
                -- Sit 1: No obligatorio según índice (no aplica al cargo/servicio)
                WHEN eb.ES_OBLIGATORIO = 0 THEN 1

                -- Si está subsanado por Control de Calidad
                WHEN eb.ID_CONTROL_CALIDAD IS NOT NULL THEN
                    CASE 
                        WHEN eb.VENC_EFECTIVO < @FechaCorte THEN 5 -- Vencido
                        WHEN eb.VENC_EFECTIVO < DATEADD(day, @VentanaDias, @FechaCorte) THEN 3 -- Por vencer
                        ELSE 2 -- Vigente
                    END

                -- Sit 9: Obligatorio según índice pero sin columna en sede
                WHEN eb.LECTURA = 'SIN_COLUMNA' THEN 9

                -- Sin fechas registradas
                WHEN eb.VENC_EFECTIVO IS NULL AND eb.REAL_EFECTIVA IS NULL THEN 
                    CASE 
                        WHEN eb.MARCA_ORIGEN IN ('SI', 'S') THEN 6
                        WHEN eb.MARCA_ORIGEN IN ('N/A', 'NA') THEN 8
                        ELSE 7
                    END

                -- Con fecha de vencimiento anterior al corte
                WHEN eb.VENC_EFECTIVO < @FechaCorte THEN 
                    CASE 
                        WHEN eb.MARCA_ORIGEN IN ('SI', 'S') THEN 4
                        ELSE 5
                    END

                -- Con fecha de vencimiento posterior o igual al corte
                ELSE 
                    CASE 
                        WHEN eb.MARCA_ORIGEN IN ('NO', 'N') THEN 10
                        WHEN eb.VENC_EFECTIVO < DATEADD(day, @VentanaDias, @FechaCorte) THEN 3
                        ELSE 2
                    END
            END AS SITUACION_NUM
        FROM EvaluacionBase eb
    )

            ON cc.CEDULA COLLATE DATABASE_DEFAULT = u.CEDULA COLLATE DATABASE_DEFAULT
           AND cc.CURSO_ID COLLATE DATABASE_DEFAULT = u.CURSO_ID COLLATE DATABASE_DEFAULT
           AND cc._activo = 1

            c.ESTADO,
            c.CARGO_NORMALIZADO,
            ISNULL(c.COD_SERVICIO, '') AS COD_SERVICIO,
            ISNULL(c.NOMBRE_SERVICIO, '') AS NOMBRE_SERVICIO,
            ISNULL(c.[JEFE INMEDIATO], 'SIN DATO') AS JEFE_INMEDIATO,
            'NO' AS MULTISEDE,
            v.CURSO_ID,
            v.CURSO_PLANTILLA,
            CASE 
                WHEN UPPER(LTRIM(RTRIM(ISNULL(v.MARCA_ORIGEN, '')))) IN ('SI_V', 'S_V', 'SI', 'S', '1', 'TRUE') THEN 'SI'
